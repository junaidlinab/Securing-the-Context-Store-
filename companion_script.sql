-- ============================================================
-- Securing the Context Store
-- Anonymization, Masking, and PII Protection on SAP HANA Cloud
-- Companion script
-- ============================================================
--
-- WHAT THIS SCRIPT DOES
-- ---------------------
-- An enterprise RAG context store holds sensitive business content
-- that will eventually be sent to an external LLM. This script shows
-- how to protect that content on SAP HANA Cloud BEFORE it leaves the
-- SAP boundary, using the database's native security features against
-- a small financial-reporting context store.
--
-- It demonstrates five techniques, each on the same dataset:
--   1. Dynamic data masking      — hide identifying columns per privilege
--   2. K-anonymity               — generalize quasi-identifiers
--   3. L-diversity               — protect a sensitive structured attribute
--   4. Differential privacy      — add calibrated noise to numeric signals
--   5. Row-level security        — scope retrieval to a user's own rows
--
-- WHAT IS ACHIEVED
-- ----------------
-- After running the script, the same context store can be queried
-- through views that mask metadata, generalize department identity,
-- noise sensitive counts, and restrict rows by department — while a
-- vector-similarity retrieval query still returns useful, grounded
-- results. Structured columns are protected inside HANA; the free-text
-- body (an NCLOB) is protected separately at the PII-detection layer,
-- covered by the companion Python script.
--
-- PREREQUISITES
-- -------------
--   * SAP HANA Cloud instance with the Vector Engine enabled
--   * Data Privacy / anonymization features enabled
--   * Embedding model available: SAP_NEB.20240715
--   * Privilege to create tables, views, roles, and masks
--
-- HOW TO RUN
-- ----------
-- Run this file top to bottom in the SAP HANA database explorer SQL
-- console (or hdbsql / DBeaver) connected to your HANA Cloud instance.
-- No application server or external service is required for the SQL.
-- To see masking take effect, run the verification SELECTs as a user
-- WITHOUT the UNMASKED privilege on the table.
-- ============================================================


