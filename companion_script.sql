-- ============================================================
-- DYNAMIC DATA MASKING
-- ============================================================
-- Masks identifying columns so users without the UNMASKED privilege
-- see redacted values. Masking is applied at table level and is
-- inherited by every view over the table. HANA masks character
-- columns; the NCLOB text body is handled at the PII layer instead.

ALTER TABLE "FIN_REPORT_CONTEXT" ADD MASK ("DOC_ID" USING 'XXXX-MASKED');
ALTER TABLE "FIN_REPORT_CONTEXT" ADD MASK ("AUTHOR" USING 'REDACTED');

-- Verify as a user WITHOUT the UNMASKED privilege:
SELECT "ID", "DOC_ID", "AUTHOR", "DEPARTMENT",
       LEFT("CHUNK_TEXT", 80) AS "CHUNK_PREVIEW"
FROM "FIN_REPORT_CONTEXT";
-- DOC_ID and AUTHOR return masked values; the text body remains
-- visible, which is why the PII-detection layer complements masking.


-- ============================================================
-- K-ANONYMITY
-- ============================================================
-- Generalizes DEPARTMENT to 'Business' through an embedded hierarchy
-- so no single department value makes a record uniquely identifiable.

CREATE VIEW "FIN_REPORT_KANON" (
    "ID",
    "DEPARTMENT",
    "CHUNK_TEXT"
)
AS
SELECT
    "ID",
    "DEPARTMENT",
    "CHUNK_TEXT"
FROM "FIN_REPORT_CONTEXT"
WITH ANONYMIZATION (
    ALGORITHM 'K-ANONYMITY'
    PARAMETERS '{"k":2}'
    COLUMN "ID"
    PARAMETERS '{"is_sequence": true}'
    COLUMN "DEPARTMENT"
    PARAMETERS '{
        "is_quasi_identifier": true,
        "hierarchy": {
            "embedded": [
                ["Finance","Business"],
                ["Compliance","Business"],
                ["Internal Audit","Business"]
            ]
        }
    }'
);

REFRESH VIEW "FIN_REPORT_KANON" ANONYMIZATION;

SELECT "DEPARTMENT", LEFT("CHUNK_TEXT",80) AS "CHUNK_PREVIEW"
FROM "FIN_REPORT_KANON";
-- DEPARTMENT is generalized to 'Business' across all rows, so a chunk
-- can no longer be traced to a specific department.


-- ============================================================
-- L-DIVERSITY
-- ============================================================
-- Extends k-anonymity by requiring diversity in a sensitive structured
-- attribute (FILING_TYPE) within each equivalence class.

CREATE VIEW "FIN_REPORT_LDIV" (
    "ID",
    "DEPARTMENT",
    "FILING_TYPE"
)
AS
SELECT
    "ID",
    "DEPARTMENT",
    "FILING_TYPE"
FROM "FIN_REPORT_CONTEXT"
WITH ANONYMIZATION (
    ALGORITHM 'L-DIVERSITY'
    PARAMETERS '{"l":2}'
    COLUMN "ID"
    PARAMETERS '{"is_sequence": true}'
    COLUMN "DEPARTMENT"
    PARAMETERS '{
        "is_quasi_identifier": true,
        "hierarchy": {
            "embedded": [
                ["Finance","Business"],
                ["Compliance","Business"],
                ["Internal Audit","Business"]
            ]
        }
    }'
    COLUMN "FILING_TYPE"
    PARAMETERS '{"is_sensitive": true}'
);

REFRESH VIEW "FIN_REPORT_LDIV" ANONYMIZATION;

SELECT "DEPARTMENT", "FILING_TYPE" FROM "FIN_REPORT_LDIV";


-- ============================================================
-- DIFFERENTIAL PRIVACY
-- ============================================================
-- Adds calibrated noise to a numeric signal (retrieval frequency) so
-- individual values cannot be read off, while aggregate trends survive.

CREATE VIEW "FIN_REPORT_DP" (
    "ID",
    "RETRIEVAL_COUNT"
)
AS
SELECT
    "ID",
    "RETRIEVAL_COUNT"
FROM "FIN_REPORT_CONTEXT"
WITH ANONYMIZATION (
    ALGORITHM 'DIFFERENTIAL_PRIVACY'
    PARAMETERS ''
    COLUMN "ID"
    PARAMETERS '{"is_sequence": true}'
    COLUMN "RETRIEVAL_COUNT"
    PARAMETERS '{"is_sensitive": true, "epsilon": 0.5, "sensitivity": 50}'
);

REFRESH VIEW "FIN_REPORT_DP" ANONYMIZATION;

SELECT "RETRIEVAL_COUNT" FROM "FIN_REPORT_DP";
-- The noised output differs substantially from the true counts, so an
-- analyst cannot infer how often any one chunk is accessed. Department-
-- level trends remain usable; per-row values do not.


-- ============================================================
-- ROW-LEVEL SECURITY (RETRIEVAL-SHAPED)
-- ============================================================
-- Scopes retrieval to a department through a view. The vector search
-- runs against the view, so a user only ever retrieves their own
-- department's rows, however semantically similar other rows are.
-- The column masks still apply through the view.

CREATE ROLE COMPLIANCE_READER;

CREATE VIEW "FIN_REPORT_COMPLIANCE" AS
SELECT "ID", "DOC_ID", "AUTHOR", "SECTION", "CHUNK_TEXT", "CHUNK_VECTOR", "IS_ACTIVE"
FROM "FIN_REPORT_CONTEXT"
WHERE "DEPARTMENT" = 'Compliance';

GRANT SELECT ON "FIN_REPORT_COMPLIANCE" TO COMPLIANCE_READER;

-- A compliance user's retrieval query (bind the user's question to ?):
SELECT TOP 3
    "DOC_ID",
    "SECTION",
    "CHUNK_TEXT",
    COSINE_SIMILARITY("CHUNK_VECTOR",
        VECTOR_EMBEDDING(?, 'QUERY', 'SAP_NEB.20240715')
    ) AS "SCORE"
FROM "FIN_REPORT_COMPLIANCE"
WHERE "IS_ACTIVE" = 'Y'
ORDER BY "SCORE" DESC;

-- Finance counterpart, same pattern:
CREATE VIEW "FIN_REPORT_FINANCE" AS
SELECT "ID", "DOC_ID", "AUTHOR", "SECTION", "CHUNK_TEXT", "CHUNK_VECTOR", "IS_ACTIVE"
FROM "FIN_REPORT_CONTEXT"
WHERE "DEPARTMENT" = 'Finance';


